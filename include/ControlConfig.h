#pragma once  // 防止本头文件被重复包含

#include <array>

// 集中管理力控参数、启停超时、传感器处理参数和开关地址。
namespace ControlConfig {

// ==================== 控制周期 ====================

// 导纳积分步长，单位：秒。
// 0.001表示每次导纳计算按1毫秒积分。
// 当前为固定积分步长，不会自动跟随实际循环耗时变化。
constexpr double DT = 0.001;

// 运行、启动、停机和清零状态的主循环周期，单位：纳秒。
// 1000000纳秒 = 1毫秒，目标频率为1000次/秒。
// 修改运行周期时，应同时检查上面的导纳积分步长。
constexpr long CONTROL_PERIOD_NS = 1000000L;

// 力控关闭和故障状态的主循环周期，单位：纳秒。
// 200000000纳秒 = 200毫秒，目标频率为5次/秒。
// 当前显示更新也由主循环执行，因此此参数会影响空闲时的显示刷新速度。
constexpr long IDLE_PERIOD_NS = 200000000L;

// 力控运行时允许的最大相邻循环间隔，单位：毫秒。
// 超过此时间，触发故障停机；启动、停机和空闲状态不使用此检查。
constexpr int MAX_CONTROL_GAP_MS = 10;


// ==================== 力传感器处理 ====================

// 一阶低通滤波系数。
// 滤波值 = 上次滤波值 + 系数 ×（当前原始值 - 上次滤波值）。
// 越大响应越快，越小越平滑但延迟越大；滤波效果也受采样周期影响。
constexpr double FILTER_ALPHA = 0.03;

// 小量程传感器的平移力死区，作用于三个平移方向。
// 绝对值不超过死区时输出0，超过时减去死区宽度。
constexpr double SMALL_FORCE_DEAD_ZONE = 1.0;

// 小量程传感器的末端旋转力矩死区。
constexpr double SMALL_MOMENT_DEAD_ZONE = 0.2;

// 大量程传感器的平移力死区。
constexpr double LARGE_FORCE_DEAD_ZONE = 2.0;

// 大量程传感器的末端旋转力矩死区。
constexpr double LARGE_MOMENT_DEAD_ZONE = 0.5;

// 滤波、死区处理后，允许进入导纳计算的单方向平移力绝对值上限。
// 单位沿用传感器换算后的力单位。
constexpr double MAX_FORCE = 50.0;

// 允许进入导纳计算的末端旋转力矩绝对值上限。
// 单位沿用传感器换算后的力矩单位。
constexpr double MAX_MOMENT = 2.0;


// ==================== 导纳控制参数 ====================

// 以下四维参数顺序均为：工具坐标系平移X、Y、Z，以及末端旋转。

// 导纳虚拟速度上限。
// 前三项单位：米/秒；第四项单位：弧度/秒。
// 对应50毫米/秒、50毫米/秒、30毫米/秒、约10度/秒。
// 这是导纳计算的速度限制，不保证真机一定能达到该速度。
const std::array<double, 4> MAX_VELOCITY = {{
    0.05, 0.05, 0.03, 0.174533
}};

// 导纳虚拟质量，第四项为虚拟转动惯量。
// 在其余条件相同时，数值越大，相同净输入产生的加速度越小。
const std::array<double, 4> MASS = {{
    130.0, 130.0, 120.0, 5.0
}};

// 导纳虚拟阻尼。
// 刚度为0且未触发速度限幅时，恒定输入下的稳态速度约为输入力/阻尼。
// 数值越大，持续推动时的稳态速度通常越小。
const std::array<double, 4> DAMPING = {{
    4000.0, 3000.0, 5000.0, 120.0
}};

// 导纳虚拟刚度。
// 全为0表示不通过弹簧项把虚拟位置拉回期望位置。
// 松手后由阻尼使速度逐渐衰减。
const std::array<double, 4> STIFFNESS = {{
    0.0, 0.0, 0.0, 0.0
}};


// ==================== 关节目标限位 ====================

// 以下四项对应关节数组下标0、1、2、3，即第1～第4关节。
// 旋转轴采用度；直线轴采用控制器配置的关节位置单位。
// 发送前检查目标是否越界，越界触发限位报警和故障停机。
// 这是软件目标检查，不替代控制器自身的硬限位。
const std::array<double, 4> JOINT_MIN = {{
    -44.0, -820.0, 5.0, -60.0
}};

const std::array<double, 4> JOINT_MAX = {{
    44.0, 1148.0, 848.0, 60.0
}};


// ==================== 关节跟踪约束 ====================

// 以下三个数组传给NRC_RKG_Open，按接口要求保留7个轴参数。
// 前四项用于本项目的四个有效关节。
// 单位及直线轴换算应按厂家接口和控制器配置确认，不能直接当作末端速度。

// 各轴跟踪速度上限。
const std::array<double, 7> TRACKING_VELOCITY = {{
    60, 60, 60, 60, 20, 20, 20
}};

// 各轴跟踪加速度上限。
const std::array<double, 7> TRACKING_ACCELERATION = {{
    1500, 1500, 1500, 1500, 2000, 2000, 2000
}};

// 各轴跟踪加加速度上限，即加速度变化率上限。
const std::array<double, 7> TRACKING_JERK = {{
    2000, 2000, 2000, 2000, 2000, 2000, 2000
}};


// ==================== 使能和停机确认 ====================

// 等待伺服使能或下使能状态确认的超时时间，单位：毫秒。
// 上使能等待状态3；下使能确认状态0或1，状态2报警不算成功。
constexpr int SERVO_TIMEOUT_MS = 1000;

// 停止轨迹生成后，等待机器人停稳的最长时间，单位：毫秒。
// 超时进入故障锁定，不直接执行下使能。
constexpr int STOP_TIMEOUT_MS = 3000;

// 停稳检查的采样间隔，单位：毫秒。
constexpr int STOP_SAMPLE_MS = 10;

// 要求机器人连续保持稳定的时间，单位：毫秒。
// 必须同时满足运动状态为停止、位置读取有效且四轴变化不超过阈值。
constexpr int STOP_STABLE_MS = 100;

// 四个关节相对本次稳定窗口参考位置的最大允许变化量。
// 单位与各自关节位置单位一致。
// 任一关节超过阈值，就更新参考位置并重新累计稳定时间。
const std::array<double, 4> STOP_POSITION_TOLERANCE = {{
    0.01, 0.01, 0.01, 0.01
}};


// ==================== 传感器清零 ====================

// 开始清零后，正式采样前的等待时间，单位：毫秒。
constexpr int ZERO_WARMUP_MS = 10;

// 清零采样间隔，单位：毫秒。
// 每到采样时间读取一组大小量程原始数据，不阻塞等待。
constexpr int ZERO_SAMPLE_MS = 2;

// 清零采样次数。
// 采满后分别求平均值，作为两个传感器各通道的新零点。
constexpr int ZERO_SAMPLE_COUNT = 50;

// 整个清零过程的超时时间，单位：毫秒。
// 清零失败、取消或超时，不覆盖上一次有效零点。
constexpr int ZERO_TIMEOUT_MS = 1000;


// ==================== 传感器显示 ====================

// 采集新一组传感器显示数据的目标间隔，单位：毫秒。
// 小量程写入变量7～12，大量程写入变量13～18。
// 当前实现每轮主循环只写一个变量，因此实际整组刷新时间也受主循环周期限制。
// 空闲周期为200毫秒时，12个变量完整轮换约需2.4秒。
constexpr int FEEDBACK_PERIOD_MS = 500;


// ==================== 控制器开关及报警地址 ====================

// 力控总开关的布尔变量编号：1为请求开启，0为请求关闭。
// 启动需要先观察到关闭，再检测到开启。
constexpr int FORCE_SWITCH_VAR = 1;

// 传感器清零开关的布尔变量编号。
// 检测从0变为1的上升沿，持续为1不会重复清零。
constexpr int ZERO_SWITCH_VAR = 2;

// 关节目标超限报警的布尔变量编号，超限时写入1。
constexpr int LIMIT_ALARM_VAR = 4;

// 传感器选择的布尔变量编号：1选择小量程，0选择大量程。
constexpr int SMALL_SENSOR_VAR = 5;

// 位置/旋转模式选择开关所在的数字输入板号。
constexpr int MODE_BOARD = 1;

// 位置/旋转模式选择开关所在的数字输入通道号。
// 此通道读到1选择末端旋转模式，读到0选择位置模式。
constexpr int MODE_CHANNEL = 1;

}  // 力控参数命名空间